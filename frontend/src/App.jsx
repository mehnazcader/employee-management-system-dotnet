
import { useEffect, useRef, useState } from 'react'
import './App.css'

// Existing backend endpoint
const API_URL = '/api/employees'

// Each department has its own permitted job titles.
const departmentJobs = {
  'Information Technology': [
    'Software Developer',
    'Software Engineer',
    'IT Support Specialist',
    'System Administrator',
    'QA Engineer',
  ],
  'Human Resources': [
    'HR Officer',
    'HR Manager',
    'Recruitment Specialist',
    'HR Assistant',
  ],
  Finance: [
    'Accountant',
    'Financial Analyst',
    'Finance Officer',
    'Finance Manager',
  ],
  Marketing: [
    'Marketing Executive',
    'Digital Marketing Specialist',
    'Marketing Manager',
    'Content Specialist',
  ],
  Operations: [
    'Operations Coordinator',
    'Operations Manager',
    'Operations Analyst',
    'Administrative Officer',
  ],
  Sales: [
    'Sales Executive',
    'Sales Representative',
    'Sales Manager',
    'Account Manager',
  ],
}

// The Employee ID is generated by SQL Server,
// so it is not included in the form.
const emptyEmployee = {
  fullName: '',
  email: '',
  department: '',
  jobTitle: '',
  isActive: true,
}

function App() {
  // React state
  // Store the list of employees retrieved from the backend.
  const [employees, setEmployees] = useState([])
  // Store the values entered in the employee form.
  const [form, setForm] = useState({ ...emptyEmployee })
  // Track which employee is being edited, or null when adding.
  const [editingId, setEditingId] = useState(null)
  // Track whether employee data is loading.
  const [loading, setLoading] = useState(true)
  // Track whether the form is being submitted.
  const [saving, setSaving] = useState(false)
  // Store error messages to display to the user.
  const [error, setError] = useState('')
  // Store success messages to display to the user.
  const [message, setMessage] = useState('')
  // Reference the form so we can scroll to it when editing.
  const formRef = useRef(null)

  // GET: Retrieve all employees from the API.
  async function loadEmployees() {
    setLoading(true)
    setError('')

    try {
      const response = await fetch(API_URL)

      if (!response.ok) {
        throw new Error('Could not load employees.')
      }

      const data = await response.json()
      setEmployees(data)
    } catch (err) {
      setError(err.message)
    } finally {
      setLoading(false)
    }
  }

  // Retrieve employees automatically when the page loads.
  useEffect(() => {
    let cancelled = false

    fetch(API_URL)
      .then((response) => {
        if (!response.ok) {
          throw new Error('Could not load employees.')
        }

        return response.json()
      })
      .then((data) => {
        if (!cancelled) {
          setEmployees(data)
        }
      })
      .catch((err) => {
        if (!cancelled) {
          setError(err.message)
        }
      })
      .finally(() => {
        if (!cancelled) {
          setLoading(false)
        }
      })

    return () => {
      cancelled = true
    }
  }, [])

  // Update the form when the user types or selects a value.
  function handleChange(event) {
    const { name, value, type, checked } = event.target

    setForm((current) => {
      // Changing Department must clear the previous Job Title.
      if (name === 'department') {
        return {
          ...current,
          department: value,
          jobTitle: '',
        }
      }

      return {
        ...current,
        [name]: type === 'checkbox' ? checked : value,
      }
    })
  }

  // Reset the form and return to Add Employee mode.
  function resetForm() {
    setForm({ ...emptyEmployee })
    setEditingId(null)
  }

  // Display the selected employee's information in the form.
  function editEmployee(employee) {
    setEditingId(employee.id)

    setForm({
      fullName: employee.fullName,
      email: employee.email,
      department: employee.department,
      jobTitle: employee.jobTitle,
      isActive: employee.isActive,
    })

    setError('')
    setMessage('')

    formRef.current?.scrollIntoView({
      behavior: 'smooth',
      block: 'nearest',
    })
  }

  // POST: Add Employee
  // PUT: Update Employee
  async function handleSubmit(event) {
    event.preventDefault()

    setError('')
    setMessage('')

    // Prevent invalid department/job title combinations.
    if (!departmentJobs[form.department]?.includes(form.jobTitle)) {
      setError(
        'Please select a valid job title for the selected department.'
      )
      return
    }

    setSaving(true)

    const isEditing = editingId !== null
    const url = isEditing ? `${API_URL}/${editingId}` : API_URL

    try {
      const response = await fetch(url, {
        method: isEditing ? 'PUT' : 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify(form),
      })

      if (!response.ok) {
        if (response.status === 409) {
          throw new Error('An employee with this email already exists.')
        }

        if (response.status === 400) {
          throw new Error('Please check the employee information.')
        }

        if (response.status === 404) {
          throw new Error('This employee no longer exists.')
        }

        throw new Error('Could not save employee.')
      }

      resetForm()
      await loadEmployees()

      setMessage(
        isEditing
          ? 'Employee updated successfully.'
          : 'Employee added successfully.'
      )
    } catch (err) {
      setError(err.message)
    } finally {
      setSaving(false)
    }
  }

  // DELETE: Delete the selected employee after confirmation.
  async function deleteEmployee(employee) {
    const confirmed = window.confirm(
      `Are you sure you want to delete ${employee.fullName}?`
    )

    if (!confirmed) {
      return
    }

    setError('')
    setMessage('')

    try {
      const response = await fetch(`${API_URL}/${employee.id}`, {
        method: 'DELETE',
      })

      if (!response.ok) {
        throw new Error('Could not delete employee.')
      }

      if (editingId === employee.id) {
        resetForm()
      }

      await loadEmployees()
      setMessage('Employee deleted successfully.')
    } catch (err) {
      setError(err.message)
    }
  }

  // Show employee initials in a simple visual avatar.
  function getInitials(fullName) {
    return fullName
      .trim()
      .split(/\s+/)
      .slice(0, 2)
      .map((part) => part.charAt(0).toUpperCase())
      .join('')
  }

  // The job title options depend on the selected department.
  const availableJobs = departmentJobs[form.department] || []

  // Previously saved records might contain older values.
  // Show those values while editing, so they are visible.
  const existingDepartment =
    form.department && !departmentJobs[form.department]
      ? form.department
      : null

  const existingJobTitle =
    editingId !== null &&
    form.jobTitle &&
    !availableJobs.includes(form.jobTitle)
      ? form.jobTitle
      : null

  return (
    <div className="app-shell">

      {/* Sidebar */}
      <aside className="sidebar">
        <div className="brand">
          <div className="brand-icon">EM</div>

          <div className="brand-text">
            <strong>Employee</strong>
            <span>Management System</span>
          </div>
        </div>

        <p className="sidebar-label">WORKSPACE</p>

        <div className="sidebar-current">
          <span className="sidebar-symbol" aria-hidden="true">
            ▦
          </span>

          <span>Employees</span>
        </div>

        <div className="sidebar-footer">
          <div className="footer-symbol" aria-hidden="true">
            ✦
          </div>

          <strong>Employee Management</strong>

          <p>
            A simple solution for managing employee records.
          </p>
        </div>
      </aside>

      {/* Main content */}
      <main className="main-content">

        {/* Header */}
        <header className="top-header">
          <div>
            <p className="eyebrow">EMPLOYEE DIRECTORY</p>

            <h1>Employee Management System</h1>

            <p className="subtitle">
              Create, view, update and delete employee records.
            </p>
          </div>

          <div
            className="header-decoration"
            aria-hidden="true"
          >
            ✦
          </div>
        </header>

        {/* Feedback messages */}
        {error && (
          <div className="alert error" role="alert">
            {error}
          </div>
        )}

        {message && (
          <div className="alert success" role="status">
            {message}
          </div>
        )}

        <div className="content-grid">

          {/* Employee Directory */}
          <section className="panel directory-panel">

            <div className="section-header">
              <div>
                <p className="section-kicker">
                  EMPLOYEE RECORDS
                </p>

                <h2>Employee Directory</h2>

                <p className="section-description">
                  View and manage registered employees.
                </p>
              </div>

              <span className="count">
                {employees.length} employees
              </span>
            </div>

            {/* Existing Refresh functionality */}
            <div className="directory-toolbar">
              <button
                type="button"
                className="secondary"
                onClick={loadEmployees}
                disabled={loading}
              >
                Refresh Employees
              </button>
            </div>

            {/* Employee Table */}
            {loading ? (
              <div className="empty-state">
                Loading employees...
              </div>
            ) : employees.length === 0 ? (
              <div className="empty-state">
                <div
                  className="empty-symbol"
                  aria-hidden="true"
                >
                  ◎
                </div>

                <h3>No employees found</h3>

                <p>
                  Add your first employee using the form.
                </p>
              </div>
            ) : (
              <div className="table-wrapper">
                <table>
                  <thead>
                    <tr>
                      <th>ID</th>
                      <th>Full Name</th>
                      <th>Email</th>
                      <th>Department</th>
                      <th>Job Title</th>
                      <th>Status</th>
                      <th>Actions</th>
                    </tr>
                  </thead>

                  <tbody>
                    {employees.map((employee) => (
                      <tr key={employee.id}>

                        <td className="id-cell">
                          #{employee.id}
                        </td>

                        <td>
                          <div className="employee-name-cell">
                            <span
                              className="avatar"
                              aria-hidden="true"
                            >
                              {getInitials(employee.fullName)}
                            </span>

                            <strong>
                              {employee.fullName}
                            </strong>
                          </div>
                        </td>

                        <td className="email-cell">
                          {employee.email}
                        </td>

                        <td>{employee.department}</td>

                        <td>{employee.jobTitle}</td>

                        <td>
                          <span
                            className={
                              employee.isActive
                                ? 'status active'
                                : 'status inactive'
                            }
                          >
                            {employee.isActive
                              ? 'Active'
                              : 'Inactive'}
                          </span>
                        </td>

                        <td>
                          <div className="row-actions">

                            <button
                              type="button"
                              className="secondary"
                              onClick={() => editEmployee(employee)}
                            >
                              Edit
                            </button>

                            <button
                              type="button"
                              className="danger"
                              onClick={() => deleteEmployee(employee)}
                            >
                              Delete
                            </button>

                          </div>
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </section>

          {/* Add/Edit Employee Form */}
          <section
            className="panel form-panel"
            ref={formRef}
          >
            <div className="form-heading">
              <div
                className="form-heading-icon"
                aria-hidden="true"
              >
                {editingId !== null ? '✎' : '+'}
              </div>

              <div>
                <h2>
                  {editingId !== null
                    ? 'Edit Employee'
                    : 'Add New Employee'}
                </h2>

                <p className="section-description">
                  {editingId !== null
                    ? 'Update the employee details below.'
                    : 'Fill in the employee details below.'}
                </p>
              </div>
            </div>

            <form
              className="employee-form"
              onSubmit={handleSubmit}
            >

              {/* Full Name */}
              <div className="field">
                <label htmlFor="fullName">
                  Full Name *
                </label>

                <input
                  id="fullName"
                  name="fullName"
                  type="text"
                  placeholder="Enter full name"
                  value={form.fullName}
                  onChange={handleChange}
                  required
                />
              </div>

              {/* Email */}
              <div className="field">
                <label htmlFor="email">
                  Email Address *
                </label>

                <input
                  id="email"
                  name="email"
                  type="email"
                  placeholder="Enter email address"
                  value={form.email}
                  onChange={handleChange}
                  required
                />
              </div>

              {/* Department Dropdown */}
              <div className="field">
                <label htmlFor="department">
                  Department *
                </label>

                <select
                  id="department"
                  name="department"
                  value={form.department}
                  onChange={handleChange}
                  required
                >
                  {/* Initial prompt, not a selectable department */}
                  <option value="" disabled hidden>
                    Select department
                  </option>

                  {Object.keys(departmentJobs).map((department) => (
                    <option
                      key={department}
                      value={department}
                    >
                      {department}
                    </option>
                  ))}

                  {/* Display older department values when editing */}
                  {existingDepartment && (
                    <option
                      value={existingDepartment}
                      disabled
                    >
                      {existingDepartment} (existing value)
                    </option>
                  )}
                </select>
              </div>

              {/* Job Title Dropdown */}
              <div className="field">
                <label htmlFor="jobTitle">
                  Job Title *
                </label>

                <select
                  id="jobTitle"
                  name="jobTitle"
                  value={form.jobTitle}
                  onChange={handleChange}
                  disabled={!form.department}
                  required
                >
                  {/* Initial prompt, not a selectable job title */}
                  <option value="" disabled hidden>
                    {form.department
                      ? 'Select job title'
                      : 'Select a department first'}
                  </option>

                  {/* Only show job titles for selected department */}
                  {availableJobs.map((jobTitle) => (
                    <option
                      key={jobTitle}
                      value={jobTitle}
                    >
                      {jobTitle}
                    </option>
                  ))}

                  {/* Display older job titles when editing */}
                  {existingJobTitle && (
                    <option
                      value={existingJobTitle}
                      disabled
                    >
                      {existingJobTitle} (existing value)
                    </option>
                  )}
                </select>
              </div>

              {/* Employee Status */}
              <div className="field">
                <label className="status-label">
                  Status
                </label>

                <label className="checkbox-field">
                  <input
                    name="isActive"
                    type="checkbox"
                    checked={form.isActive}
                    onChange={handleChange}
                  />

                  <span>Active employee</span>
                </label>
              </div>

              {/* Form Actions */}
              <div className="form-actions">

                <button
                  type="submit"
                  className="primary-button"
                  disabled={saving}
                >
                  {saving
                    ? 'Saving...'
                    : editingId !== null
                      ? 'Save Changes'
                      : '+ Add Employee'}
                </button>

                {editingId !== null && (
                  <button
                    type="button"
                    className="secondary"
                    onClick={resetForm}
                    disabled={saving}
                  >
                    Cancel Editing
                  </button>
                )}

              </div>
            </form>
          </section>

        </div>
      </main>
    </div>
  )
}

export default App
